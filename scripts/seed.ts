import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { generateSeedLeads, type SeedLead } from "../lib/seed-data";

/** Writes supabase/seed.sql from the deterministic generator in lib/seed-data.ts. */

const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const b = (v: boolean) => (v ? "true" : "false");
const ago = (min: number, extraSec = 0) =>
  `now() - interval '${min} minutes'${extraSec ? ` + interval '${extraSec} seconds'` : ""}`;
const arr = (xs: string[]) => `ARRAY[${xs.map(q).join(", ")}]::text[]`;
const json = (o: unknown) => `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb`;

function leadSql(l: SeedLead, n: number): string[] {
  const out: string[] = [];
  const created = ago(l.minutesAgo);
  const last = l.messages[l.messages.length - 1];
  out.push(
    `insert into sessions (id, visitor_id, ip_hash, user_agent, source, language_detected, mode, started_at, last_active_at, ended_at) values (${q(l.sessionId)}, ${q(`seed-visitor-${n}`)}, null, 'seed', 'seed', ${q(l.lang)}, 'live', ${created}, ${ago(l.minutesAgo, last.offsetSec)}, ${ago(l.minutesAgo, last.offsetSec)});`,
  );
  for (const m of l.messages) {
    out.push(
      `insert into messages (session_id, role, content, tokens_in, tokens_out, model, created_at) values (${q(l.sessionId)}, ${q(m.role)}, ${q(m.content)}, ${m.tokensIn}, ${m.tokensOut}, ${m.role === "assistant" ? "'claude-haiku-5-5'" : "null"}, ${ago(l.minutesAgo, m.offsetSec)});`,
    );
    if (m.role === "assistant") {
      out.push(
        `insert into usage_logs (session_id, provider, model, tokens_in, tokens_out, cost_inr, created_at) values (${q(l.sessionId)}, 'anthropic', 'claude-haiku-5-5', ${m.tokensIn}, ${m.tokensOut}, ${m.costInr}, ${ago(l.minutesAgo, m.offsetSec)});`,
      );
    }
  }
  const demo =
    l.demo_days_ahead !== null && l.demo_time
      ? `(current_date + ${l.demo_days_ahead}) + time '${l.demo_time}'`
      : "null";
  out.push(
    `insert into leads (id, session_id, student_name, parent_name, parent_phone, phone_valid, class_or_exam, board, preferred_branch, preferred_batch, budget_comfort, interest_summary, score, badge, score_reasons, next_action, needs_human, handover_reason, demo_slot_requested, status, is_seed, created_at, updated_at) values (${q(l.id)}, ${q(l.sessionId)}, ${q(l.student_name)}, ${q(l.parent_name)}, ${q(l.parent_phone)}, ${b(l.phone_valid)}, ${q(l.class_or_exam)}, ${q(l.board)}, ${q(l.preferred_branch)}, ${q(l.preferred_batch)}, ${q(l.budget_comfort)}, ${q(l.interest_summary)}, ${l.score}, ${q(l.badge)}, ${arr(l.score_reasons)}, ${q(l.next_action)}, ${b(l.needs_human)}, ${q(l.handover_reason)}, ${demo}, ${q(l.status)}, true, ${created}, ${ago(l.minutesAgo, last.offsetSec)});`,
  );
  out.push(
    `insert into lead_events (lead_id, event_type, old_value, new_value, created_at) values (${q(l.id)}, 'score_changed', ${json({ score: 0 })}, ${json({ score: l.score })}, ${ago(l.minutesAgo, last.offsetSec)}), (${q(l.id)}, 'badge_changed', ${json({ badge: "COLD" })}, ${json({ badge: l.badge })}, ${ago(l.minutesAgo, last.offsetSec)});`,
  );
  if (l.needs_human) {
    out.push(
      `insert into lead_events (lead_id, event_type, old_value, new_value, created_at) values (${q(l.id)}, 'handover', null, ${json({ reason: l.handover_reason })}, ${ago(l.minutesAgo, last.offsetSec)});`,
    );
  }
  if (l.badge === "HOT") {
    out.push(
      `insert into alerts (lead_id, channel, title, body, shown, created_at) values (${q(l.id)}, 'whatsapp_mock', 'New HOT lead', ${q(`🔥 New HOT lead: ${l.parent_name ?? "Parent"}, ${l.class_or_exam ?? "enquiry"}${l.demo_slot_label ? `, wants demo ${l.demo_slot_label}` : ""}`)}, true, ${ago(l.minutesAgo, last.offsetSec)});`,
    );
  }
  return out;
}

const leads = generateSeedLeads();
const sql = [
  "-- GENERATED by scripts/seed.ts — do not edit by hand. Run: npm run db:seed",
  "-- 40 fictional seed leads over the last 14 days. All names and phones are fake.",
  "delete from sessions where source = 'seed';",
  ...leads.flatMap((l, i) => leadSql(l, i + 1)),
  "",
].join("\n");

const target = resolve(__dirname, "../supabase/seed.sql");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, sql, "utf8");

const count = (k: string) => leads.filter((l) => l.badge === k).length;
console.log(`Wrote ${target}: ${leads.length} leads (HOT ${count("HOT")}, WARM ${count("WARM")}, COLD ${count("COLD")}), ${leads.reduce((s, l) => s + l.messages.length, 0)} messages`);
